X_train,X_test, y_train, y_test = train_test_split(X, y, test_size=0.3, random_state=1357)
train_df = pd.merge(left=X_train, right=y_train, left_index=True, right_index=True)
test_df = pd.merge(left=X_test, right=y_test, left_index=True, right_index=True)
train_df

#  θ(N/3*N/7)=N^2. Long run time on colab on original file. sample reduced to 1500 rows.
def Calc(count, V): # calculating P(V|number exist)
  if V==0 and count ==0:
    return 1
  if V/(count)>0.5:
    return 'V'
  return 'N'

def CountExist(row,train_df): # For each row in test sample, check for each row in the train test. For example, if 4 exist return count of 4 in the train test and the count V's of 4 for prediction. The same for 1,2,3 and 0.
  count1=0
  count2=0
  count3=0
  count4=0
  V1=0
  V2=0
  V3=0
  V4=0
  maxx=0
  arr=[row['W1'],row['W2'],row['W3'],row['W4']]

  for index,TrainRow in train_df.iterrows():
    if(arr[2]==TrainRow['W3']):
      if(TrainRow['True Value']=='V'):
            V1+=1
      count=1
      for i in range(0,len(arr)):

        if ((i is not 2) and (arr[i] == TrainRow.iloc[i])) and count==1:
          count=2
          if(TrainRow['True Value']=='V'):
            V2+=1
          continue

        if ((i is not 2) and (arr[i] == TrainRow.iloc[i])) and count==2 :
          count=3
          if(TrainRow['True Value']=='V'):
            V3+=1
          continue
        if ((i is not 2) and (arr[i] == TrainRow.iloc[i])) and count==3:
          if(TrainRow['True Value']=='V'):
            V4+=1
          count=4

      if count==4:
        count4+=1
      if count==3:
        count3+=1
      if count==2:
        count2+=1
      if count==1:
        count1+=1

  maxV=0
  maxCount=0

  if count1>0:
    maxV=V1
    maxCount=count1

  if count2>0:
    maxV=V2
    maxCount=count2

  if count3>0:
    maxV=V3
    maxCount=count3

  if count4>0:
    maxV=V4
    maxCount=count4

  return Calc(maxCount,maxV)

test_df['Predict']=test_df.apply (lambda row: CountExist(row,train_df), axis=1)

test_df


#splitting
import pandas as pd
from sklearn.model_selection import train_test_split
data = pd.DataFrame(NewList)


data=data.iloc[:, 0: 5]
data.rename(columns = {0:'W1', 1:'W2',2:'W3',3:'W4',4:'True Value'}, inplace = True)

import pandas as pd

# Assuming df is your existing DataFrame with columns: viewed_impressions, impressions

def calculate_viewability_tier(row):
    if row['impressions'] == 0:
        return 'Invalid'
    viewability = row['viewed_impressions'] / row['impressions']
    if viewability < 0.35:
        return 'Low Viewability'
    elif 0.35 <= viewability <= 0.65:
        return 'Medium Viewability'
    elif viewability > 0.65:
        return 'High Viewability'
    else:
        return 'Invalid'

# Add viewability tier column to df
df['viewability_tier'] = df.apply(calculate_viewability_tier, axis=1)

# Display the updated DataFrame with viewability tier
print(df.head())

# Count the number of occurrences of each viewability tier
tier_counts = df['viewability_tier'].value_counts()

# Calculate percentages of total
total_entries = len(df)
tier_percentages = (tier_counts / total_entries) * 100

# Plotting the distribution with percentages
plt.figure(figsize=(10, 6))
ax = sns.countplot(x='viewability_tier', data=df, palette='viridis')
plt.title('Distribution of Viewability Tiers', fontsize=16, fontweight='bold')
plt.xlabel('Viewability Tier', fontsize=14)
plt.ylabel('Count', fontsize=14)
plt.xticks(rotation=45, ha='right', fontsize=12)
plt.yticks(fontsize=12)

# Add percentages on top of each bar
for p, percentage in zip(ax.patches, tier_percentages):
    height = p.get_height()
    ax.text(p.get_x() + p.get_width() / 2.,
            height + 0.5,
            f'{percentage:.1f}%',
            ha='center', va='bottom', fontsize=10, color='black')

plt.tight_layout()
plt.show()
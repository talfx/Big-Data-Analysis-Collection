import pandas as pd

def top_urls_by_pageviews(device_type, geo_location, df):
    # Filter data by device type and geo location
    filtered_df = df[(df['device_type'] == device_type) & (df['geo_location'] == geo_location)]

    # Group by URL and calculate total pageviews
    url_pageviews = filtered_df.groupby('URL')['pageviews'].sum().reset_index()

    # Sort URLs by pageviews in descending order
    url_pageviews_sorted = url_pageviews.sort_values(by='pageviews', ascending=False)

    # Get top 3 URLs
    top_urls = url_pageviews_sorted.head(3)

    return top_urls

